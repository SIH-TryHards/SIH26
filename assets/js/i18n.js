const PACKS = { en, hi, mr, bn, ta, te };

let current = 'en';

export function setLang(code) {
  if (PACKS[code]) current = code;
  return current;
}

export function getLang() {
  return current;
}

/* Falls back to English, then to the key itself so missing strings
   surface in dev instead of blank UI. */
export function t(key, params = {}) {
  const template = PACKS[current]?.[key] ?? PACKS.en[key] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name) =>
    params[name] === undefined || params[name] === null ? '' : String(params[name]));
}
